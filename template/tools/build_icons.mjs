// Bundle the icons the page uses into js/icons.js (inline SVG, so the page works from file://).
//   node tools/build_icons.mjs
// Sources: assets/icons/phosphor/{regular,light,duotone}/*.svg  — Phosphor Icons, MIT
//          assets/icons/simple-icons/*.svg                      — Simple Icons, CC0
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>[\s\S]*?<\/title>/, '');
const out = { regular: {}, light: {}, duotone: {}, brand: {} };
const svgs = (dir) => (existsSync(dir) ? readdirSync(dir).filter((x) => x.endsWith('.svg')) : []);
for (const w of ['regular', 'light', 'duotone']) {
  const dir = join(root, 'assets', 'icons', 'phosphor', w);
  for (const f of svgs(dir)) out[w][f.slice(0, -4)] = inner(readFileSync(join(dir, f), 'utf8'));
}
const bdir = join(root, 'assets', 'icons', 'simple-icons');
for (const f of svgs(bdir)) out.brand[f.slice(0, -4)] = inner(readFileSync(join(bdir, f), 'utf8'));

const js = `/* icons.js — generated by tools/build_icons.mjs. Phosphor Icons (MIT) and Simple Icons (CC0). */
(function () {
  const I = ${JSON.stringify(out)};
  /** inline SVG markup for an icon: weight = regular | light | duotone | brand */
  function icon(name, weight) {
    const w = weight || 'regular';
    const body = (I[w] || {})[name];
    if (body === undefined) throw new Error('icon not bundled: ' + w + '/' + name);
    return '<svg viewBox="0 0 ' + (w === 'brand' ? '24 24' : '256 256') + '" fill="currentColor" aria-hidden="true">' + body + '</svg>';
  }
  /** replace every <i data-ph="name" data-w="weight"> under root with the icon */
  function hydrate(root) {
    for (const el of (root || document).querySelectorAll('[data-ph]')) {
      el.classList.add('ph');
      el.innerHTML = icon(el.dataset.ph, el.dataset.w);
    }
  }
  window.OXICON = { icon, hydrate };
})();
`;
writeFileSync(join(root, 'js', 'icons.js'), js);
console.log('js/icons.js:', Object.entries(out).map(([k, v]) => `${Object.keys(v).length} ${k}`).join(', '), `(${(js.length / 1024).toFixed(0)} KB)`);
